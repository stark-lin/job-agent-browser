const assert = require('node:assert/strict')
const { mkdtempSync, rmSync, readFileSync, existsSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { randomUUID } = require('node:crypto')
const { spawnSync } = require('node:child_process')
const { Client } = require('@modelcontextprotocol/client')
const { StdioClientTransport } = require('@modelcontextprotocol/client/stdio')
const { createBackend } = require('../.cache/tests/src/platform/database/backend.js')
const { extractPdf } = require('../.cache/tests/src/platform/import/pdf.js')
const { nativeMCPEnvironment } = require('../.cache/tests/src/platform/mcp/native-environment.js')
const { jobAgentAllowlist } = require('../.cache/tests/src/platform/tools/index.js')

async function until(check, message) {
  const deadline = Date.now() + 10000
  while (!check()) { if (Date.now() > deadline) throw new Error(message); await new Promise(resolve => setTimeout(resolve, 20)) }
}
async function main() {
  const directory = mkdtempSync(join(tmpdir(), 'resume-mcp-smoke-')), entry = resolve(__dirname, '../out/main/job-agent-mcp.js')
  const { SmartNoteWorkspace } = require('../.cache/tests/src/platform/knowledge/workspace.js')
  const { defaultKnowledgePreferences } = require('../.cache/tests/src/shared/knowledge-settings.js')
  const workspace = new SmartNoteWorkspace(directory, { preferences: () => defaultKnowledgePreferences })
  await workspace.ready
  const backend = createBackend(join(directory, 'database.sqlite'))
  const dispatch = (group, method, input) => { const result = backend.dispatch(group, method, input); assert(result.ok, result.error); return result.value }
  const job = dispatch('jobs', 'saveJob', { details: { title: 'TypeScript Engineer', companyNameRaw: 'Offline Fixture', description: 'Build reliable TypeScript services and test them.' } })
  const profile = dispatch('profiles', 'createProfile', { name: 'MCP Resume Fixture', email: 'fixture@example.com' })
  const item = dispatch('profiles', 'addItem', { profileId: profile.id, details: { type: 'EXPERIENCE', title: 'Engineer', organization: 'Fixture Team' } })
  const fact = dispatch('profiles', 'addFact', { profileId: profile.id, profileItemId: item.id, details: { kind: 'ACHIEVEMENT', content: 'Built TypeScript services with automated tests.' } })
  const baseline = backend.resumes.createRun({ jobId: job.id, profileId: profile.id }, { start: true })
  const client = new Client({ name: 'codex-smoke', version: '1' })
  const protocolErrors = []
  client.onerror = error => protocolErrors.push(error)
  const transport = new StdioClientTransport({ command: process.execPath, args: [entry], cwd: resolve(__dirname, '..'), env: { ...nativeMCPEnvironment(), JOB_BROWSER_USER_DATA: directory }, stderr: 'pipe', maxBufferSize: 2097152 })
  let diagnostics = ''
  transport.stderr?.on('data', chunk => { if (diagnostics.length < 4000) diagnostics += chunk })
  const call = async (name, args) => { const result = await client.callTool({ name, arguments: args }, { timeout: 100000 }); assert(!result.isError, JSON.stringify(result)); return result.structuredContent }
  try {
    await client.connect(transport)
    assert.deepEqual((await client.listTools()).tools.map(tool => tool.name).sort(), [...jobAgentAllowlist].sort())
    assert.equal(backend.resumes.getRun({ id: baseline.id }).run.state, 'REWRITING', 'MCP startup must preserve another process task')
    assert.equal((await call('job.list', {})).items[0].id, job.id)
    assert.equal((await call('profile.list', {})).items[0].id, profile.id)
    await until(() => diagnostics.includes('[TOOL] job.list SUCCESS'), 'Tool diagnostics did not reach stderr')
    assert.deepEqual(protocolErrors, [], 'MCP stdout must contain only protocol messages')
    assert(!diagnostics.includes(job.title)); assert(!diagnostics.includes(profile.email))
    // Exercise the built profile surface, not only the compiled test runtime.
    const imported = await call('profile.create', { requestId: randomUUID(), details: { name: 'Distillation fixture', email: 'keep@example.com' } })
    const updated = await call('profile.update', { id: imported.id, requestId: randomUUID(), expectedRevision: imported.revision, changes: { phone: '123' } })
    assert.equal(updated.email, imported.email)
    const projectRequest = { profileId: imported.id, requestId: randomUUID(), expectedRevision: updated.revision, details: { type: 'PROJECT', title: 'Inspected repository' } }
    const project = await call('profile.add_item', projectRequest)
    assert.deepEqual(await call('profile.add_item', projectRequest), project)
    const changedProject = await call('profile.update_item', { id: project.id, profileId: imported.id, requestId: randomUUID(), expectedRevision: project.revision, changes: { metadata: { technologies: ['TypeScript'] } } })
    const sourceFact = await call('profile.add_fact', { profileId: imported.id, profileItemId: project.id, requestId: randomUUID(), expectedRevision: changedProject.revision, details: { kind: 'OTHER', content: 'Project validates structured inputs.' } })
    const changedFact = await call('profile.update_fact', { id: sourceFact.id, profileId: imported.id, requestId: randomUUID(), expectedRevision: sourceFact.revision, changes: { tags: ['validation'] } })
    assert(!('evidence' in changedFact)); assert(!('evidence' in sourceFact)); assert.equal(changedFact.profileItemId, project.id)
    assert.equal((await call('profile.list_items', { profileId: imported.id })).items[0].id, project.id)
    const { runId } = await call('resume.start', { jobId: job.id, profileId: profile.id, requestId: randomUUID() })
    dispatch('profiles', 'editContact', { id: profile.id, details: { name: 'LIVE PROFILE CHANGED' } })
    const context = await call('resume.get_context', { runId }), facts = await call('resume.list_facts', { runId })
    assert.equal(context.profile.name, profile.name); assert.equal(facts.total, 1)
    const page = await call('resume.list_bullets', { runId })
    const rewrite = { runId, bulletId: page.items[0].bulletId, text: 'Built TypeScript services and automated tests.', requestId: randomUUID() }
    const receipt = await call('resume.rewrite_bullet', rewrite)
    assert.equal(receipt.changed, true)
    assert.deepEqual(await call('resume.rewrite_bullet', rewrite), receipt)
    const { artifact } = await call('resume.publish', { runId })
    const built = await call('artifact.build', { artifactId: artifact.id })
    assert.equal(built.output.status, 'READY', `Worker output failed: ${JSON.stringify(built)} ${diagnostics}`)
    for (const file of built.files) assert(existsSync(file.path))
    const html = readFileSync(built.files.find(file => file.format === 'HTML').path, 'utf8')
    const pdf = readFileSync(built.files.find(file => file.format === 'PDF').path)
    assert(html.includes(profile.name)); assert(html.includes(rewrite.text)); assert.equal(pdf.subarray(0, 5).toString(), '%PDF-')
    const pages = await extractPdf(new Uint8Array(pdf), new AbortController().signal, () => {}, resolve(__dirname, '../out/main/pdf-worker.mjs'))
    assert.equal(pages.length, built.output.pages); assert(pages.map(page => page.text).join(' ').includes('TypeScript services'))
    const view = await call('artifact.get', { id: artifact.id })
    assert.deepEqual(view.provenance, [{ blockId: rewrite.bulletId, factIds: [fact.id] }])
    assert.equal(backend.resumes.getRun({ id: runId }).run.config.runtimeKind, 'external')
    assert.equal(backend.resumes.getRun({ id: runId }).run.config.providerId, '')
    const editedContent = structuredClone(view.artifact.content)
    editedContent.basics.links = [{ label: 'Portfolio', url: 'portfolio.example/my work' }]
    Object.assign(editedContent.experience[0], { startDate: 'Summer 2020 (part-time)', endDate: 'After graduation', url: 'github.com/example/project' })
    const edited = dispatch('resumes', 'editArtifact', { id: artifact.id, title: artifact.title, expectedRevision: view.artifact.revision, content: editedContent })
    assert.equal(edited.revision, 2)
    const rebuilt = await call('artifact.build', { artifactId: artifact.id })
    assert.equal(rebuilt.output.status, 'READY')
    const saved = await call('artifact.get', { id: artifact.id })
    assert.equal(saved.artifact.revision, 2)
    assert.deepEqual(saved.artifact.content, editedContent)
    const editedHtml = readFileSync(rebuilt.files.find(file => file.format === 'HTML').path, 'utf8')
    for (const text of ['portfolio.example/my work', 'Summer 2020 (part-time)', 'After graduation', 'github.com/example/project']) assert(editedHtml.includes(text))
    const editedPdf = readFileSync(rebuilt.files.find(file => file.format === 'PDF').path)
    const editedPages = await extractPdf(new Uint8Array(editedPdf), new AbortController().signal, () => {}, resolve(__dirname, '../out/main/pdf-worker.mjs'))
    const editedText = editedPages.map(page => page.text).join(' ')
    for (const text of ['portfolio.example/my work', 'Summer 2020 (part-time)', 'After graduation', 'github.com/example/project']) assert(editedText.includes(text))
    // The still-open parent backend remains independently writable.
    const cancel = new AbortController(), cancelled = client.callTool({ name: 'artifact.build', arguments: { artifactId: artifact.id } }, { signal: cancel.signal })
    await until(() => backend.resumes.getArtifact({ id: artifact.id }).artifact.output.status === 'RUNNING', 'Second build did not start')
    cancel.abort(); await assert.rejects(cancelled)
    await until(() => backend.resumes.getArtifact({ id: artifact.id }).artifact.output.status === 'CANCELLED', 'Cancelled worker did not settle')
    assert.equal((await call('artifact.build', { artifactId: artifact.id })).output.status, 'READY')
    const unfinished = await call('resume.start', { jobId: job.id, profileId: profile.id, requestId: randomUUID() })
    const pid = transport.pid
    await client.close()
    await until(() => { try { process.kill(pid, 0); return false } catch { return true } }, 'MCP process remained alive after EOF')
    backend.recover()
    assert.equal(backend.resumes.getRun({ id: unfinished.runId }).run.state, 'INTERRUPTED')
    assert.equal(backend.resumes.getRun({ id: baseline.id }).run.state, 'REWRITING')
    const crashed = new Client({ name: 'crash-smoke', version: '1' })
    const crashTransport = new StdioClientTransport({ command: process.execPath, args: [entry], env: { ...nativeMCPEnvironment(), JOB_BROWSER_USER_DATA: directory }, stderr: 'ignore' })
    try {
      await crashed.connect(crashTransport)
      const result = await crashed.callTool({ name: 'resume.start', arguments: { jobId: job.id, profileId: profile.id, requestId: randomUUID() } })
      assert(!result.isError)
      process.kill(crashTransport.pid, 'SIGKILL')
      await until(() => { try { process.kill(crashTransport.pid, 0); return false } catch { return true } }, 'Crashed MCP process was not reaped')
      backend.recover()
      assert.equal(backend.resumes.getRun({ id: result.structuredContent.runId }).run.state, 'INTERRUPTED')
      assert.equal(backend.resumes.getRun({ id: baseline.id }).run.state, 'REWRITING')
    } finally { await crashed.close() }
    const env = { ...process.env }; delete env.JOB_BROWSER_USER_DATA
    const missing = spawnSync(process.execPath, [entry], { env, encoding: 'utf8', timeout: 10000 })
    assert.equal(missing.status, 1); assert.equal(missing.stdout, ''); assert(missing.stderr.includes('MCP_DATA_REQUIRED'))
    console.log('Outbound MCP smoke passed: built Node stdio entry, shared SQLite across processes, immutable snapshot, full external workflow, real Electron HTML/PDF worker, PDF text/page validation, cancellation/rebuild, EOF/crash recovery and zero application model calls.')
  } finally { await client.close().catch(() => {}); backend.close(); await workspace.close(); rmSync(directory, { recursive: true, force: true }) }
}
void main().catch(error => { console.error(error); process.exitCode = 1 })
